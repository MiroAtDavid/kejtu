"""Foreground reminder capability over the existing durable reminder owner."""
from typing import Protocol


class RemindersPort(Protocol):
    def epoch(self): ...
    def guard(self, conversation_id, turn_id, ledger): ...
    def execute(self, args, *, cid, tid, ledger, budget, reads, notices): ...
    def history_actions(self, past_turn, *, cid, tid, ledger): ...
