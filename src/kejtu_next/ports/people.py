"""Explicit people access under the foreground ledger."""
from typing import Protocol


class PeoplePort(Protocol):
    def epoch(self, ledger=None): ...
    def guard(self, conversation_id, writing=False, ledger=None): ...
    def execute(self, args, *, conversation_id, turn_id, operation_key, ledger,
                maximum, budget=None, read_refs=frozenset()) -> dict: ...
    def history_actions(self, turn_id, ledger) -> list[dict]: ...
