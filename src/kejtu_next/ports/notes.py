"""Explicit owned-note persistence; application supplies the existing turn ledger."""
from typing import Protocol

from ..core.budget import Ledger, SearchBudget
from ..core.memory import MemorySnapshot
from ..core.notes import NoteResult, NoteScope
from ..core.records import ToolCall


class NotesPort(Protocol):
    def history_actions(self, snapshot: MemorySnapshot, turn_id: str, ledger: Ledger) -> dict: ...
    def scope(self, snapshot: MemorySnapshot, turn_id: str, ledger: Ledger) -> NoteScope: ...
    def scope_job(self, snapshot: MemorySnapshot, run_id: str, ledger: Ledger) -> NoteScope: ...
    def inspect_run(self, snapshot: MemorySnapshot, run_id: str, ledger: Ledger, *, limit=20, after=''): ...
    def write(self, scope: NoteScope, call: ToolCall, ledger: Ledger, maximum: int,
              *, budget: SearchBudget | None = None) -> NoteResult: ...
    def save(self, scope: NoteScope, call: ToolCall, target: tuple[str, str] | None,
             ledger: Ledger, maximum: int, *, budget: SearchBudget | None = None) -> NoteResult: ...
    def outcome(self, snapshot: MemorySnapshot, call: ToolCall, ledger: Ledger,
                maximum: int, *, budget: SearchBudget | None = None) -> dict: ...
