"""Explicit read-only bank access, independently of conversation history."""
from typing import Protocol

from ..core.budget import Ledger, SearchBudget
from ..core.memory import MemorySnapshot


class MemoryPort(Protocol):
    def automatic_query(self, snapshot: MemorySnapshot, question: str, ledger: Ledger) -> str: ...
    async def prepare(self, snapshot: MemorySnapshot, query: str, ledger: Ledger) -> None: ...
    def snapshot(self, conversation_id: str, bank_id: str, ledger: Ledger) -> MemorySnapshot: ...
    def research_snapshot(self, conversation_id: str, bank_id: str, ledger: Ledger) -> MemorySnapshot: ...
    def job_snapshot(self, run_id: str, ledger: Ledger) -> MemorySnapshot: ...
    def check(self, snapshot: MemorySnapshot, ledger: Ledger) -> None: ...
    def search(self, snapshot: MemorySnapshot, args: dict, ledger: Ledger, maximum: int, *, budget: SearchBudget | None = None) -> dict: ...
    def read(self, snapshot: MemorySnapshot, args: dict, ledger: Ledger, maximum: int) -> dict: ...
