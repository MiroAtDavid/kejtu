from typing import Protocol
from .web import WebSources
from ..core.records import Conversation, Message, Profile, Reply, ToolCall, Turn
from ..core.reference import ReferencePage
from ..core.budget import Ledger, SearchBudget
from ..core.history import HistorySnapshot, HistoryUnit
from ..core.execution import HistoryPolicy


class Store(Protocol):
    """Completed answers and required provider state commit atomically.

    history supplies paired state only where the saved conversation requires it,
    validates integrity and obeys allowance using the shared message-cost owner.
    Missing state is a failure, not permission to synthesize or omit it. turns
    remains the visible-answer projection and never exposes raw provider state.
    """
    web: WebSources
    def imported_conversation(self, conversation_id: str) -> bool: ...
    def require_writable_conversation(self, conversation_id: str) -> None: ...
    async def maintain_memory(self) -> None: ...
    def record_recall_admission(self, turn_id: str, result: dict) -> None: ...
    def create_conversation(self, profile: Profile, system_prompt: str, *, reference_body: str | None = None, history_enabled: bool = False, history_policy: HistoryPolicy | None = None, memory_enabled: bool = False, notes_enabled: bool = False, hybrid_memory: bool = False, tasks_enabled: bool = False, request_counter=None, provider_first: bool = False, mutation_key: str | None = None, intent_sha256: str | None = None) -> str: ...
    def note_outcomes(self, turn_id: str) -> dict: ...
    def preview_note_removal(self, conversation_id: str, note_id: str) -> dict: ...
    def remove_note(self, conversation_id: str, note_id: str, preview_token: str, operation_id: str) -> dict: ...
    def note_removal_status(self, conversation_id: str, operation_id: str, *, include_intent: bool = False) -> dict: ...
    def notebook_page(self, conversation_id: str, cursor: str | None = None, limit: int = 20) -> dict: ...
    def notebook_read(self, conversation_id: str, note_id: str, revision_id: str, view_token: str, offset: int, maximum: int) -> dict: ...
    def note_removal_preview_page(self, conversation_id: str, note_id: str, start: int = 0, limit: int = 20, expected_token: str | None = None) -> dict: ...
    def conversation(self, conversation_id: str) -> Conversation: ...
    def start(self, conversation_id: str, user: str, *, mutation_key: str | None = None,
              intent_sha256: str | None = None, expected_previous_turn_id: str | None = None) -> str: ...
    def turn(self, turn_id: str) -> Turn: ...
    def history(self, turn_id: str, allowance: int) -> tuple[Message, ...]: ...
    def history_snapshot(self, turn_id: str, ledger: Ledger) -> HistorySnapshot: ...
    def delivery_epoch(self) -> int: ...
    def history_unit(self, snapshot: HistorySnapshot, ledger: Ledger, *, ordinal: int | None = None, turn_id: str | None = None) -> HistoryUnit: ...
    def history_load(self, snapshot: HistorySnapshot, unit: HistoryUnit, ledger: Ledger) -> tuple[Message, ...]: ...
    def save_admission(self, snapshot: HistorySnapshot, record: dict) -> None: ...
    def admission(self, turn_id: str) -> dict | None: ...
    def history_operation(self, snapshot: HistorySnapshot, name: str, args, ledger: Ledger, maximum: int, *, budget: SearchBudget | None = None) -> dict: ...
    def start_operation(self, snapshot: HistorySnapshot, ordinal: int, call: ToolCall, *, preflight_rejected: bool = False) -> None: ...
    def prepare_operation(self, snapshot: HistorySnapshot, ordinal: int, result: dict) -> None: ...
    def submit_operation(self, snapshot: HistorySnapshot, ordinal: int) -> None: ...
    def dispatched(self, turn_id: str, input_estimate: int, call_number: int = 1) -> None: ...
    def observed(self, turn_id: str, call_number: int, reply: Reply) -> None: ...
    def context_event(self, turn_id: str, record: dict) -> None: ...
    def context_rejected(self, turn_id: str, call_number: int) -> None: ...
    def note_argument_failure(self, turn_id: str, call_number: int, batch_position: int,
                              call: ToolCall, validation_reason: str) -> None: ...
    def memory_argument_failure(self, turn_id: str, call_number: int, batch_position: int,
                                call: ToolCall, validation_reason: str) -> None: ...

    def history_argument_failure(self, turn_id: str, call_number: int, batch_position: int,
                                call: ToolCall, validation_reason: str) -> None: ...
    def read_reference(self, conversation_id: str, offset: int, maximum: int, deadline: float) -> ReferencePage: ...
    def start_read(self, turn_id: str, call: ToolCall) -> None: ...
    def finish_read(self, turn_id: str, page: ReferencePage) -> None: ...
    def submit_read(self, turn_id: str) -> None: ...
    def reads(self, turn_id: str) -> tuple[dict, ...]: ...
    def finish(self, turn_id: str, status: str, *, reason: str | None = None,
               detail: str | None = None, reply: Reply | None = None) -> Turn: ...
    def turns(self, conversation_id: str, *, after: int = 0, limit: int = 50) -> tuple[Turn, ...]: ...
