"""Replaceable search providers and independent page extraction, no model client."""
from typing import Protocol


class SearchProvider(Protocol):
    name: str
    categories: tuple[str, ...]
    async def search(self, arguments: dict, *, deadline: float) -> dict: ...


class PageReader(Protocol):
    async def read(self, url: str, *, deadline: float) -> dict: ...


class SearchUsage(Protocol):
    def begin(self, provider: str) -> str: ...
    def finish(self, identity: str, outcome: str, elapsed_ms: int, result_count: int = 0) -> None: ...
    def status(self, provider: str) -> dict: ...


class WebSources(Protocol):
    usage: SearchUsage
    def settings(self) -> dict: ...
    def guard(self, conversation_id: str, revision: int): ...
    def save(self, turn_id: str, provider: str, kind: str, request: dict, metadata: dict, content: str) -> str: ...
    def load(self, source_id: str, conversation_id: str, *, manual: bool = False) -> dict: ...
    def history_actions(self, turn_id: str) -> list[dict]: ...
